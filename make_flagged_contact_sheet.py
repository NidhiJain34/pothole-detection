#!/usr/bin/env python3
"""
Create a contact sheet of flagged images from the cleaned pothole dataset.

READ-ONLY: does not modify, move, rename, or delete dataset images or labels.
Uses image_sanity_details.csv generated by image_sanity_check.py.

Outputs:
  flagged_image_contact_sheets/flagged_small_01.jpg, ...
  flagged_image_contact_sheets/flagged_large_01.jpg, ...
  flagged_image_contact_sheets/flagged_samples_with_boxes_01.jpg, ...
  flagged_image_contact_sheets/visual_inspection_summary.txt

Run with the project's virtual environment:
  .venv/bin/python make_flagged_contact_sheet.py
"""

from pathlib import Path
import csv
import math
import random
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("ERROR: Pillow is missing. Install it with:")
    print('  "/home/CL502-13/Downloads/latestmergedproject2.v1i.yolo26/.venv/bin/python" -m pip install Pillow')
    sys.exit(1)

ROOT = Path("/home/CL502-13/Downloads/latestmergedproject2.v1i.yolo26")
DATASET = ROOT / "final_cleaned_dataset_no_conflicts"
CSV_PATH = ROOT / "image_sanity_details.csv"
OUT_DIR = ROOT / "flagged_image_contact_sheets"

# Contact-sheet layout. The source images are only copied into report sheets;
# the dataset itself is never edited.
THUMB_W = 240
THUMB_H = 170
CELL_W = 270
CELL_H = 225
COLS = 4
MAX_PER_CATEGORY = 120
RANDOM_SEED = 42

def load_font(size=13):
    try:
        return ImageFont.truetype("DejaVuSans.ttf", size)
    except Exception:
        return ImageFont.load_default()

def parse_label(label_path):
    boxes = []
    if not label_path.is_file():
        return boxes, "MISSING LABEL"
    try:
        content = label_path.read_text(encoding="utf-8").strip()
    except Exception:
        return boxes, "LABEL READ ERROR"
    if not content:
        return boxes, "EMPTY LABEL / BACKGROUND"
    for line_no, line in enumerate(content.splitlines(), 1):
        parts = line.split()
        if len(parts) != 5:
            return boxes, f"INVALID LINE {line_no}"
        try:
            cls = int(float(parts[0]))
            xc, yc, bw, bh = map(float, parts[1:])
        except ValueError:
            return boxes, f"INVALID VALUES {line_no}"
        # YOLO format coordinates are normalized to [0, 1].
        if not (0 <= xc <= 1 and 0 <= yc <= 1 and 0 < bw <= 1 and 0 < bh <= 1):
            return boxes, f"OUT-OF-RANGE BOX {line_no}"
        boxes.append((cls, xc, yc, bw, bh))
    return boxes, f"{len(boxes)} BOX(ES)"

def find_label_path(image_path):
    # image path is .../<split>/images/<relative image filename>
    parts = image_path.parts
    try:
        idx = parts.index("images")
    except ValueError:
        return None
    return Path(*parts[:idx], "labels", *parts[idx + 1:]).with_suffix(".txt")

def draw_boxes(image, boxes):
    draw = ImageDraw.Draw(image)
    font = load_font(12)
    w, h = image.size
    for cls, xc, yc, bw, bh in boxes:
        x1 = max(0, int((xc - bw / 2) * w))
        y1 = max(0, int((yc - bh / 2) * h))
        x2 = min(w - 1, int((xc + bw / 2) * w))
        y2 = min(h - 1, int((yc + bh / 2) * h))
        # Use default drawing colours so no colour scheme is forced.
        draw.rectangle((x1, y1, x2, y2), outline="red", width=max(2, w // 400))
        draw.text((x1 + 2, max(0, y1 - 14)), f"class {cls}", fill="red", font=font)
    return image

def make_sheet(entries, out_path, title, show_boxes=False):
    if not entries:
        return 0
    rows = math.ceil(len(entries) / COLS)
    sheet = Image.new("RGB", (COLS * CELL_W, rows * CELL_H), "white")
    draw = ImageDraw.Draw(sheet)
    title_font = load_font(15)
    body_font = load_font(11)

    for i, row in enumerate(entries):
        image_path = ROOT / row["image"]
        x = (i % COLS) * CELL_W
        y = (i // COLS) * CELL_H
        try:
            with Image.open(image_path) as source:
                im = source.convert("RGB")
                original_size = im.size
                if show_boxes:
                    label_path = find_label_path(image_path)
                    boxes, label_status = parse_label(label_path) if label_path else ([], "NO LABEL PATH")
                    im = draw_boxes(im, boxes)
                else:
                    label_path = find_label_path(image_path)
                    _, label_status = parse_label(label_path) if label_path else ([], "NO LABEL PATH")
                im.thumbnail((THUMB_W, THUMB_H))
                px = x + (CELL_W - im.width) // 2
                py = y + 5
                sheet.paste(im, (px, py))
                draw.text((x + 6, y + THUMB_H + 8), f'{row["split"]} | {original_size[0]}x{original_size[1]}', fill="black", font=title_font)
                draw.text((x + 6, y + THUMB_H + 30), Path(row["image"]).name[:36], fill="black", font=body_font)
                draw.text((x + 6, y + THUMB_H + 47), label_status, fill="black", font=body_font)
        except Exception as exc:
            draw.text((x + 6, y + 10), f'Could not open: {Path(row["image"]).name}', fill="black", font=body_font)
            draw.text((x + 6, y + 28), str(exc)[:45], fill="black", font=body_font)

    sheet.save(out_path, quality=90)
    return len(entries)

def main():
    if not DATASET.is_dir():
        sys.exit(f"ERROR: Dataset not found: {DATASET}")
    if not CSV_PATH.is_file():
        sys.exit(
            f"ERROR: {CSV_PATH} not found.\n"
            "Run image_sanity_check.py first, then rerun this script."
        )

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    all_rows = []
    with CSV_PATH.open("r", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            try:
                w = int(row["width_px"])
                h = int(row["height_px"])
            except (ValueError, TypeError, KeyError):
                continue
            row["_width"] = w
            row["_height"] = h
            row["_pixels"] = w * h
            row["_path"] = ROOT / row["image"]
            all_rows.append(row)

    # Flag exactly the same thresholds used by the prior sanity checker.
    small = [r for r in all_rows if r["_width"] < 320 or r["_height"] < 320]
    large = [r for r in all_rows if r["_width"] > 4096 or r["_height"] > 4096]
    small = sorted(small, key=lambda r: (r["_pixels"], r["image"]))
    large = sorted(large, key=lambda r: (-r["_pixels"], r["image"]))

    rng = random.Random(RANDOM_SEED)
    # Inspect up to 120 smallest images, and up to 120 largest images.
    small_sample = small[:MAX_PER_CATEGORY]
    large_sample = large[:MAX_PER_CATEGORY]

    # For annotated examples, sample flagged images that have labels with boxes.
    annotated_flagged = [
        r for r in all_rows
        if (r["_width"] < 320 or r["_height"] < 320 or r["_width"] > 4096 or r["_height"] > 4096)
        and r.get("label_status") == "ANNOTATED"
    ]
    rng.shuffle(annotated_flagged)
    annotated_sample = annotated_flagged[:min(48, len(annotated_flagged))]

    print("Creating contact sheets. Dataset files will not be modified.")
    print(f"Total images listed in CSV: {len(all_rows):,}")
    print(f"Flagged small images: {len(small):,}; showing the {len(small_sample):,} smallest.")
    print(f"Flagged large images: {len(large):,}; showing {len(large_sample):,}.")
    print(f"Flagged annotated images: {len(annotated_flagged):,}; showing {len(annotated_sample):,} with boxes.")

    written = []
    if small_sample:
        path = OUT_DIR / "flagged_small_01.jpg"
        make_sheet(small_sample, path, "Small images")
        written.append(path)
    if large_sample:
        path = OUT_DIR / "flagged_large_01.jpg"
        make_sheet(large_sample, path, "Large images")
        written.append(path)
    if annotated_sample:
        path = OUT_DIR / "flagged_samples_with_boxes_01.jpg"
        make_sheet(annotated_sample, path, "Flagged images with boxes", show_boxes=True)
        written.append(path)

    summary = [
        "VISUAL INSPECTION CONTACT SHEETS",
        "=" * 60,
        f"Dataset: {DATASET}",
        f"Images listed in sanity CSV: {len(all_rows):,}",
        f"Images below 320 px in width or height: {len(small):,}",
        f"Images above 4096 px in width or height: {len(large):,}",
        f"Flagged annotated images available: {len(annotated_flagged):,}",
        "",
        "Sheets created:",
        *[str(p) for p in written],
        "",
        "IMPORTANT:",
        "- This script does not change dataset images or labels.",
        "- The small sheet shows up to 120 of the smallest images.",
        "- The large sheet shows up to 120 of the largest images.",
        "- The bounding-box sheet shows a random sample of flagged annotated images.",
        "- Red rectangles represent boxes decoded from YOLO labels; they do not prove the boxes are accurate.",
        "- Review whether the boxes surround potholes and whether empty-label images truly contain no potholes.",
    ]
    summary_path = OUT_DIR / "visual_inspection_summary.txt"
    summary_path.write_text("\n".join(summary) + "\n", encoding="utf-8")
    print("\n".join(summary))
    print("\nDONE. Open the JPG contact sheets in VS Code or your file manager.")

if __name__ == "__main__":
    main()
